//! Night-only facade emission on the authored city batches.
use bevy::{
    pbr::{ExtendedMaterial, MaterialExtension},
    prelude::*,
    render::render_resource::{AsBindGroup, ShaderRef},
};

#[derive(Asset, TypePath, AsBindGroup, Debug, Clone)]
struct WindowEmission {
    /// Facade frame width/height, luminance, material seed.
    #[uniform(100)]
    panes: Vec4,
}

impl MaterialExtension for WindowEmission {
    fn fragment_shader() -> ShaderRef {
        "scene://city_windows.wgsl".into()
    }
}

type CityMaterial = ExtendedMaterial<StandardMaterial, WindowEmission>;

pub(super) fn install(app: &mut App) {
    app.add_plugins(MaterialPlugin::<CityMaterial>::default())
        .add_systems(Update, (attach_windows, update_windows).chain());
}

fn facade_style(name: &str) -> Option<usize> {
    name.strip_prefix("Toronto city batch ")?
        .strip_suffix(".0")?
        .parse::<usize>()
        .ok()
        .filter(|index| *index < 4)
}

fn attach_windows(
    mut commands: Commands,
    weather: Res<super::weather_transition::AppliedWeather>,
    assets: Res<AssetServer>,
    originals: Res<Assets<StandardMaterial>>,
    mut materials: ResMut<Assets<CityMaterial>>,
    added: Query<
        (Entity, &Name, &MeshMaterial3d<StandardMaterial>),
        Added<MeshMaterial3d<StandardMaterial>>,
    >,
) {
    // Match the four original facade textures generated by facades.py.
    let frames = [(0.055, 0.09), (0.045, 0.075), (0.18, 0.20), (0.20, 0.23)];
    for (entity, name, handle) in &added {
        let Some(index) = facade_style(name.as_str()) else {
            continue;
        };
        if !assets
            .get_path(handle.0.id())
            .is_some_and(|p| p.source().as_str() == Some("scene"))
        {
            continue;
        }
        let Some(base) = originals.get(&handle.0) else {
            continue;
        };
        let (width, height) = frames[index];
        let material = materials.add(ExtendedMaterial {
            base: base.clone(),
            extension: WindowEmission {
                panes: Vec4::new(width, height, 120.0 * weather.current.sky.z, index as f32),
            },
        });
        commands
            .entity(entity)
            .remove::<MeshMaterial3d<StandardMaterial>>()
            .insert(MeshMaterial3d(material));
        tracing::info!(target: "cc_render", "night city windows attached: {}", name);
    }
}

fn update_windows(weather: Res<super::weather_transition::AppliedWeather>, mut materials: ResMut<Assets<CityMaterial>>) {
    for (_, material) in materials.iter_mut() {
        material.extension.panes.z = 120.0 * weather.current.sky.z;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_authored_facade_primitives_receive_windows() {
        for i in 0..4 {
            assert_eq!(facade_style(&format!("Toronto city batch {i}.0")), Some(i));
        }
        for name in [
            "Toronto city batch 0.1",
            "Toronto city batch 4.0",
            "Toronto city batch 0",
            "Condo baked floor",
            "Hair.0",
        ] {
            assert_eq!(facade_style(name), None, "{name}");
        }
    }
}
