//! Transport-only scene handoffs. Boundaries refer to existing model samples;
//! this module cannot construct or edit a pose.
use super::{controller::OfficeSnapshot, motion_intent::MotionGoal};

pub(crate) const SCENE_HANDOFF_MIN_MS: u64 = 2200;

#[derive(Default)]
pub(crate) struct SceneDelivery {
    pub pending: Option<(MotionGoal, bool)>,
    reservation: Option<(String, u64, u64)>,
}
impl SceneDelivery {
    pub(crate) fn anchor(office: &OfficeSnapshot, generated_until: u64) -> Option<u64> {
        let anchor = Self::source_anchor(office.avatar.displayed_pts_ms, generated_until)?;
        (office.avatar.buffered_until_pts_ms? >= anchor).then_some(anchor)
    }

    pub(crate) fn source_anchor(displayed: u64, generated_until: u64) -> Option<u64> {
        // ACK owns the complete source-token grid. The renderer may still be
        // draining the batch and expose a partial (non-token-aligned) tail.
        // Hand off at the earliest native token at least SCENE_HANDOFF_MIN_MS ahead (the
        // new revision's first block must be generated by then), not at the end of the
        // generated buffer: a new goal takes over ~2.2 s after it is accepted.
        let earliest = displayed.checked_add(SCENE_HANDOFF_MIN_MS)?;
        let anchor = generated_until.checked_sub((generated_until.checked_sub(earliest)? / 200) * 200)?;
        Some(anchor)
    }

    pub(crate) fn request_anchor(goal: &MotionGoal, displayed: u64, end: u64) -> Option<u64> {
        if goal.scene_outcome().is_some() { return Self::source_anchor(displayed, end); }
        Self::token_anchor(displayed, end, 600, 200)
    }

    fn token_anchor(displayed: u64, end: u64, lead: u64, minimum: u64) -> Option<u64> {
        let latest = end.min(displayed.checked_add(lead)?);
        let anchor = end.checked_sub((end-latest).div_ceil(200)*200)?;
        (anchor >= displayed.checked_add(minimum)?).then_some(anchor)
    }

    pub(crate) fn reserved_for(&self, goal: &MotionGoal) -> bool {
        self.reservation.as_ref().is_some_and(|(session, revision, _)|
            session == goal.session_id() && *revision == goal.revision())
    }

    pub(crate) fn reserve(&mut self, goal: &MotionGoal, anchor: u64) {
        self.reservation = Some((goal.session_id().into(), goal.revision(), anchor));
    }

    /// Called before forwarding even the FIRST new frame to the renderer.
    /// Failure rejects delivery; it must not skip a prefix and resume halfway.
    pub(crate) fn first_frame(&mut self, session: &str, revision: u64, pts: u64, displayed: u64) -> Result<(), String> {
        let Some((expected_session, expected_revision, anchor)) = self.reservation.as_ref() else { return Ok(()) };
        if expected_session != session || *expected_revision != revision { return Ok(()); }
        if pts != anchor + 50 || displayed > *anchor {
            return Err(format!("scene delivery missed reserved native handoff: anchor={anchor} first={pts} displayed={displayed}"));
        }
        self.reservation = None;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cc_render::office::controller::OfficeController;
    fn goal() -> MotionGoal {
        serde_json::from_value(serde_json::json!({"kind":"motion_goal","version":3,
            "session_id":"test","generation_revision":2,"pts_ms":1500,"seed":42,
            "goal":{"operation":"navigate","target_id":"chair"}})).unwrap()
    }
    #[test]
    fn same_native_token_boundary_as_worker_and_insufficient_lead_is_not_ready() {
        let mut office = OfficeController::default().snapshot();
        office.avatar.displayed_pts_ms = 1500;
        office.avatar.buffered_until_pts_ms = Some(4000);
        // The earliest token at least 2.2 s ahead (3800), not the end of the buffer.
        assert_eq!(SceneDelivery::anchor(&office, 4000), Some(3800));
        assert_eq!(SceneDelivery::anchor(&office, 6000), Some(3800)); // A deeper buffer hands off just as soon.
        office.avatar.buffered_until_pts_ms = Some(3700);
        assert_eq!(SceneDelivery::anchor(&office, 4000), None); // Wait until the source token is queued.
        office.avatar.displayed_pts_ms = 1700;
        office.avatar.buffered_until_pts_ms = Some(4000);
        assert_eq!(SceneDelivery::anchor(&office, 3800), None); // Under 2.2 s of generation headroom.
    }
    #[test]
    fn semantic_anchor_matches_worker_and_keeps_latency_headroom() {
        let goal = MotionGoal::new("test".into(), 3, 1500, 42, "Wave".into()).unwrap();
        assert_eq!(SceneDelivery::request_anchor(&goal, 1500, 4000), Some(2000));
        assert_eq!(SceneDelivery::request_anchor(&goal, 200, 400), Some(400));
        assert_eq!(SceneDelivery::request_anchor(&goal, 350, 400), None);
        let mut delivery = SceneDelivery::default();
        delivery.reserve(&goal, 2000);
        assert!(delivery.reserved_for(&goal));
        assert!(delivery.first_frame("test", 3, 2050, 1800).is_ok());
        assert!(!delivery.reserved_for(&goal));
    }

    #[test]
    fn first_frame_must_arrive_before_reserved_prefix_finishes() {
        let mut delivery = SceneDelivery::default();
        delivery.reserve(&goal(), 3800);
        assert!(delivery.first_frame("test", 2, 3850, 3750).is_ok());
        delivery.reserve(&goal(), 3800);
        assert!(delivery.first_frame("test", 2, 3850, 3801).is_err());
        assert!(delivery.first_frame("test", 2, 3900, 3750).is_err());
    }
}
